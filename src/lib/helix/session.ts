function clip(id: string, start: number, duration: number, extra?: Partial<Clip>): Clip {
  return { id, start, duration, ...extra };
}

function full(id: string): Clip[] {
  return [clip(id, 0, DURATION)];
}

function track(partial: Omit<Track, "clips"> & { clips?: Clip[] }): Track {
  return {
    unused: false,
    missingMedia: false,
    unusedSilenceSec: 0,
    dcOffset: 0,
    clippingEvents: 0,
    takes: [],
    sends: [],
    automation: [],
    plugins: [],
    clips: partial.clips ?? full(`c_${partial.id}`),
    ...partial,
  };
}

