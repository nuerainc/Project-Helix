export function cloneSession(session: SessionState): SessionState {
  return structuredClone(session);
}

export function mixerTracks(session: SessionState): Track[] {
  return session.tracks.filter((t) => t.kind !== "master");
}

export function masterTrack(session: SessionState): Track {
  return session.tracks.find((t) => t.kind === "master") ?? session.tracks[session.tracks.length - 1];
}

export function findTrack(session: SessionState, id: string): Track | undefined {
  return session.tracks.find((t) => t.id === id);
}

export const trackById = findTrack;

export function chorusMarkers(session: SessionState): Marker[] {
  return session.markers.filter((m) => m.type === "chorus");
}
